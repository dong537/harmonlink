def count_cjk(text: str) -> int:
    """Count CJK unified ideographs without counting punctuation or ASCII."""
    return sum(
        "\u3400" <= character <= "\u4dbf" or "\u4e00" <= character <= "\u9fff"
        for character in text
    )
